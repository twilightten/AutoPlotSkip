# 一帧画面平均灰度低于这个值就当成黑屏/抓不到（0~255）。
# 星穹铁道的剧情画面大多很暗（实测开场 CG 平均灰度约 3），阈值开高了会
# 把正常画面判成黑屏，所以只用来挡掉「全黑 = 抓取失败」这一种情况。
MIN_FRAME_MEAN = 0.8

# 主循环间隔的下限（防止用户把 LOOP_INTERVAL 调到 0 把 CPU 打满）
